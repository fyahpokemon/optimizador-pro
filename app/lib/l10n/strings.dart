const supportedLocales = [Locale('es'), Locale('en')];

String translate(Locale locale, String key, [Map<String, String> args = const {}]) {
  final table = _strings[locale.languageCode] ?? _strings['es']!;
  var text = table[key] ?? _strings['es']![key] ?? key;
  args.forEach((k, v) => text = text.replaceAll('{$k}', v));
  return text;
}

extension Tr on BuildContext {
  String tr(String key, [Map<String, String> args = const {}]) =>
      translate(Localizations.localeOf(this), key, args);
}
